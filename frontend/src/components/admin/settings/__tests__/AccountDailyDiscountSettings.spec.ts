import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import AccountDailyDiscountSettings from '../AccountDailyDiscountSettings.vue'
const api = vi.hoisted(() => ({ get: vi.fn(), put: vi.fn() }))
vi.mock('@/api/admin/settings', () => ({ getAccountDailyDiscountSettings: api.get, updateAccountDailyDiscountSettings: api.put }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
beforeEach(() => {
  vi.clearAllMocks()
  api.get.mockResolvedValue({ enabled: false, tiers: [] })
  api.put.mockImplementation(async value => value)
})
describe('AccountDailyDiscountSettings', () => {
  it('adds multiple tiers, saves and restores them', async () => {
    const wrapper = mount(AccountDailyDiscountSettings)
    await flushPromises()
    await wrapper.get('[data-testid="add-tier"]').trigger('click')
    await wrapper.get('[data-testid="threshold-0"]').setValue('100')
    await wrapper.get('[data-testid="discount-0"]').setValue('8')
    await wrapper.get('[data-testid="add-tier"]').trigger('click')
    await wrapper.get('[data-testid="threshold-1"]').setValue('200')
    await wrapper.get('[data-testid="discount-1"]').setValue('6')
    await wrapper.get('[data-testid="discount-enabled"]').setValue(true)
    await wrapper.get('[data-testid="save-discount"]').trigger('click')
    await flushPromises()
    const value = { enabled: true, tiers: [{ threshold_usd: 100, discount: 8 }, { threshold_usd: 200, discount: 6 }] }
    expect(api.put).toHaveBeenCalledWith(value)
    expect(wrapper.get('[role="status"]').text()).toContain('accountDailyDiscount.saved')
    wrapper.unmount()
    api.get.mockResolvedValue(value)
    const restored = mount(AccountDailyDiscountSettings)
    await flushPromises()
    expect((restored.get('[data-testid="discount-1"]').element as HTMLInputElement).value).toBe('6')
    await restored.get('[data-testid="remove-0"]').trigger('click')
    expect(restored.find('[data-testid="threshold-1"]').exists()).toBe(false)
    restored.unmount()
  })
  it('rejects duplicate thresholds and enabled empty rules', async () => {
    const wrapper = mount(AccountDailyDiscountSettings)
    await flushPromises()
    await wrapper.get('[data-testid="discount-enabled"]').setValue(true)
    await wrapper.get('[data-testid="save-discount"]').trigger('click')
    expect(api.put).not.toHaveBeenCalled()
    await wrapper.get('[data-testid="add-tier"]').trigger('click')
    await wrapper.get('[data-testid="add-tier"]').trigger('click')
    await wrapper.get('[data-testid="save-discount"]').trigger('click')
    expect(api.put).not.toHaveBeenCalled()
    expect(wrapper.get('[role="alert"]').text()).toContain('accountDailyDiscount.invalid')
    wrapper.unmount()
  })
  it.each(['', '0', '11', '-1', '8.001'])('rejects invalid discount %s', async value => {
    api.get.mockResolvedValue({ enabled: true, tiers: [{ threshold_usd: 100, discount: 8 }] })
    const wrapper = mount(AccountDailyDiscountSettings)
    await flushPromises()
    await wrapper.get('[data-testid="discount-0"]').setValue(value)
    await wrapper.get('[data-testid="save-discount"]').trigger('click')
    expect(api.put).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('shows load failure without offering to overwrite with defaults', async () => {
    api.get.mockRejectedValueOnce(new Error('offline'))
    const wrapper = mount(AccountDailyDiscountSettings)
    await flushPromises()
    expect(wrapper.find('[data-testid="save-discount"]').exists()).toBe(false)
    expect(wrapper.get('[role="alert"]').text()).toContain('accountDailyDiscount.loadFailed')
    wrapper.unmount()
  })
})
